#!/usr/bin/env python3
"""brief_collision_check.py — catch a queued brief that asks for an article the site already has.

Q-2026-07-09-1 asked the box to write "Waarom lopen WMS-implementaties uit?" as "the first hub
piece". The site had published that exact title on 2026-07-08 — the same day as the visibility
audit the brief was derived from. The agent never chose the topic; it executed the brief
faithfully. So the duplicate has to be caught at the brief, not only at the draft.

queue.md is regenerated by the Mac's eod-wrap skill and agents never edit it, so this cannot fix
the generator. It is the box-side half: a read-only gate over the OPEN rows the box is about to
work, run as a pre-flight so a colliding brief is refused before an agent drafts against it.

Usage:
  brief_collision_check.py [--queue PATH] [--json] [--quiet]

Exit 0 = no collision, 2 = at least one OPEN brief collides with a published article.
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import published_corpus as corpus  # noqa: E402

DEFAULT_QUEUE = os.path.expanduser(
    os.environ.get("VP_QUEUE_PATH", "~/vault/04_operations/box_brief/queue.md"))
QUOTED_TITLE = re.compile(r"[\"“]([^\"”]{12,160})[\"”]")


def _split_row(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def parse_open_items(markdown):
    """Rows of the deadline-aware queue table (NUC-34 schema) whose Status is OPEN."""
    items = []
    for line in markdown.splitlines():
        if not line.strip().startswith("|"):
            continue
        cells = _split_row(line)
        if len(cells) < 6 or cells[0] in ("Priority", "---") or set(cells[0]) <= {"-", ":"}:
            continue
        if cells[5].upper() != "OPEN":
            continue
        items.append({"task_id": cells[1], "deadline": cells[2], "task": cells[3]})
    return items


def candidate_titles(task_text):
    """A brief names its article in quotes; fall back to the bolded lead-in."""
    quoted = QUOTED_TITLE.findall(task_text)
    if quoted:
        return quoted
    bold = re.findall(r"\*\*(.+?)\*\*", task_text)
    return bold[:1]


def evaluate(items, rows):
    results = []
    for item in items:
        for title in candidate_titles(item["task"]):
            ranked = corpus.rank(title, rows)
            top = ranked[0] if ranked else None
            if top and top["score"] >= corpus.COLLISION_THRESHOLD:
                results.append({"task_id": item["task_id"], "candidate": title,
                                "score": top["score"], "published": top})
    return results


def _report(collisions, items, fresh):
    print(corpus._freshness_line(fresh))
    print("checked {} OPEN queue item(s)".format(len(items)))
    if not collisions:
        print("\nNo OPEN brief reuses a published title. Lexical check only — an adjacent "
              "angle\nunder a different title will not show up here.")
        return
    print("\nCOLLISION — {} OPEN brief(s) ask for an already-published article:".format(
        len(collisions)))
    for c in collisions:
        p = c["published"]
        print('\n  {}  score {:.2f}\n    brief asks for : "{}"\n    already live   : [{}] {}'
              '\n    published      : {}  slug={}'.format(
                  c["task_id"], c["score"], c["candidate"], p["locale"], p["title"],
                  p["publishedAt"], p["slug"]))
    print("\nFix the brief before the box drafts against it: retarget to a distinct query, or\n"
          "restate it as an UPDATE to the existing article (bump updatedAt), not a new post.")


def main():
    p = argparse.ArgumentParser(description="Gate queued briefs against the published corpus")
    p.add_argument("--queue", default=DEFAULT_QUEUE)
    p.add_argument("--json", action="store_true")
    p.add_argument("--quiet", action="store_true", help="print only on collision")
    args = p.parse_args()

    if not os.path.isfile(args.queue):
        sys.exit("brief_collision_check: queue not found at {}".format(args.queue))
    with open(args.queue) as f:
        items = parse_open_items(f.read())
    articles, fresh = corpus.load_corpus()
    collisions = evaluate(items, corpus.entries(articles))

    if args.json:
        print(json.dumps({"freshness": fresh, "checked": len(items),
                          "collisions": collisions}, indent=2))
    elif collisions or not args.quiet:
        _report(collisions, items, fresh)
    sys.exit(2 if collisions else 0)


if __name__ == "__main__":
    main()
