#!/usr/bin/env bash
# NUC-36: model-free overnight pre-snapshot (replaces Hermes cron LLM checklist).
# Captures system state before the morning agent window. Fail-soft per section.
set -uo pipefail

OUT_DIR="${OVERNIGHT_LOG_DIR:-$HOME/logs/overnight}"
mkdir -p "$OUT_DIR"
stamp=$(date -u +%Y-%m-%dT%H%MZ)
out="$OUT_DIR/pre-snapshot-${stamp}.log"

section() {
  printf '\n## %s\n' "$1"
}

run_or_note() {
  # shellcheck disable=SC2068
  if ! "$@" 2>&1; then
    echo "(command failed: $*)"
  fi
}

{
  echo "# Overnight pre-snapshot — $stamp"
  echo "Generated by bin/overnight_pre_snapshot.sh (NUC-36, model-free)"

  section "Header"
  echo "timestamp_utc: $(date -u -Is)"
  echo "timestamp_local: $(date -Is)"
  echo "hostname: $(hostname 2>/dev/null || echo unknown)"
  echo "user: $(whoami 2>/dev/null || echo unknown)"
  run_or_note uptime

  section "MCP servers"
  if command -v hermes >/dev/null 2>&1; then
    run_or_note hermes mcp list
  else
    echo "hermes not on PATH"
  fi
  qmd_ep=down
  if command -v curl >/dev/null 2>&1 && curl -sf --max-time 2 http://127.0.0.1:8765/health >/dev/null 2>&1; then
    qmd_ep=up
  fi
  brave_ep=down
  if command -v ss >/dev/null 2>&1 && ss -ltn 2>/dev/null | grep -q ':8766'; then
    brave_ep=up
  fi
  echo "qmd_mcp_8765: $qmd_ep"
  echo "brave_mcp_8766: $brave_ep"

  # "Gateway health" and "Kanban state" sections removed 2026-09-02 with the S3
  # retirement (open-decisions.md D7). Both were wrapped in run_or_note, so they would
  # not have broken the snapshot — they would have captured a dead surface every night
  # at 04:25 and handed the morning report a diff of nothing, indefinitely. The morning
  # report's profile stops asking for a kanban diff in the same commit; a consumer left
  # asking for a section the producer no longer emits is the other half of this defect.

  section "Inbox files"
  inbox="$HOME/agent-worktrees/inbox/_inbox/agents"
  if [ -d "$inbox" ]; then
    run_or_note ls -la "$inbox"
  else
    echo "inbox missing: $inbox"
  fi

  section "Inbox lifecycle summary (agent-inbox-sync --dry-run)"
  src="$HOME/dev/agent-workforce/bin/agent_inbox_notion_sync.py"
  if [ -f "$src" ]; then
    run_or_note python3 "$src" --dry-run
  else
    echo "sync script missing: $src"
  fi

  section "Systemd timers (fleet schedule)"
  run_or_note systemctl list-timers \
    'overnight-*' 'agent-*' 'augustus-*' 'bd-*' 'weekly-*' \
    'memory-consolidation.timer' 'scorecard.timer' 'qmd-refresh.timer' \
    --no-pager

  section "Recent unit results"
  for u in overnight-pre-snapshot.service overnight-morning-report.service \
           agent-proposal.service agent-inbox-sync.service \
           augustus-content.service bd-stall-radar.service \
           weekly-pre-assembly.service; do
    echo "--- $u ---"
    systemctl show "$u" -p ActiveState -p Result -p ExecMainStatus -p ExecMainStartTimestamp \
      --value 2>/dev/null | paste -sd' ' - || echo "(unit unknown)"
  done

  section "Box clock sanity"
  run_or_note timedatectl status

  section "Disk / system"
  run_or_note df -h /home
  run_or_note free -h

  section "Alerts (last 10)"
  if [ -f "$HOME/logs/agent-alert.log" ]; then
    tail -10 "$HOME/logs/agent-alert.log" || true
  else
    echo "no agent-alert.log yet"
  fi
} >"$out" 2>&1

echo "wrote $out"
exit 0
