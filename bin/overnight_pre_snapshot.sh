#!/usr/bin/env bash
# NUC-36: model-free overnight pre-snapshot (replaces Hermes cron LLM checklist).
# Captures system state before the morning agent window. Fail-soft per section.
set -uo pipefail

OUT_DIR="${OVERNIGHT_LOG_DIR:-$HOME/logs/overnight}"
mkdir -p "$OUT_DIR"
stamp=$(date -u +%Y-%m-%dT%H%MZ)
out="$OUT_DIR/pre-snapshot-${stamp}.log"

section() {
  printf '\n## %s\n' "$1"
}

run_or_note() {
  # shellcheck disable=SC2068
  if ! "$@" 2>&1; then
    echo "(command failed: $*)"
  fi
}

# One owner for the fleet unit list (W3, 2026-09-02) — see config/fleet-units.tsv.
# Resolved relative to this script so it works from the repo and from ~/agent-workforce/;
# design/ is not deployed, so reading the manifests here would empty silently in the runtime.
FLEET_UNITS="$(dirname "$0")/../config/fleet-units.tsv"
# `kind` (column 5) is not optional here. The five buzz-agent@* rows are Type=simple
# services with no timer; appending ".timer" to them asks the manager for a unit that does
# not exist, and `systemctl list-timers` answers that by SILENTLY DROPPING the name — rc=0,
# empty stderr, "1 timers listed" for six units requested. Measured 2026-09-03.
fleet_units() {  # $1 = scope, $2 = kind (timer|service|any)
  awk -F'\t' -v want="$1" -v kind="${2:-any}" \
    '!/^#/ && NF>=5 && $2==want && $3=="standing" && (kind=="any" || $5==kind) {print $1}' \
    "$FLEET_UNITS"
}

# An EMPTY derived list must be LOUD. `NF>=5` matches nothing against a 4-column
# (pre-2026-09-03) copy of the list — which is what ~/agent-workforce/config/ still holds
# until bin/deploy runs — and `systemctl list-timers` with an empty argument array lists
# EVERY timer on the box (44, measured 2026-09-03). So the failure mode of a stale list is a
# full-looking report derived from nothing, which is strictly worse than the glob this
# replaced. Checking readability is not enough; the RESULT has to be checked.
fleet_or_die() {  # scope, kind -> prints units, or refuses
  local out
  out=$(fleet_units "$1" "$2")
  if [ -z "$out" ]; then
    echo "  FATAL: $FLEET_UNITS declares no $1/$2 units — missing, empty, or still 4-column." >&2
    echo "  Unit coverage is UNKNOWN, not 'none'." >&2
    return 1
  fi
  printf '%s\n' "$out"
}

{
  echo "# Overnight pre-snapshot — $stamp"
  echo "Generated by bin/overnight_pre_snapshot.sh (NUC-36, model-free)"

  section "Header"
  echo "timestamp_utc: $(date -u -Is)"
  echo "timestamp_local: $(date -Is)"
  echo "hostname: $(hostname 2>/dev/null || echo unknown)"
  echo "user: $(whoami 2>/dev/null || echo unknown)"
  run_or_note uptime

  section "MCP servers"
  if command -v hermes >/dev/null 2>&1; then
    run_or_note hermes mcp list
  else
    echo "hermes not on PATH"
  fi
  qmd_ep=down
  if command -v curl >/dev/null 2>&1 && curl -sf --max-time 2 http://127.0.0.1:8765/health >/dev/null 2>&1; then
    qmd_ep=up
  fi
  brave_ep=down
  if command -v ss >/dev/null 2>&1 && ss -ltn 2>/dev/null | grep -q ':8766'; then
    brave_ep=up
  fi
  echo "qmd_mcp_8765: $qmd_ep"
  echo "brave_mcp_8766: $brave_ep"

  # "Gateway health" and "Kanban state" sections removed 2026-09-02 with the S3
  # retirement (open-decisions.md D7). Both were wrapped in run_or_note, so they would
  # not have broken the snapshot — they would have captured a dead surface every night
  # at 04:25 and handed the morning report a diff of nothing, indefinitely. The morning
  # report's profile stops asking for a kanban diff in the same commit; a consumer left
  # asking for a section the producer no longer emits is the other half of this defect.

  section "Inbox files"
  inbox="$HOME/agent-worktrees/inbox/_inbox/agents"
  if [ -d "$inbox" ]; then
    run_or_note ls -la "$inbox"
  else
    echo "inbox missing: $inbox"
  fi

  section "Inbox lifecycle summary (agent-inbox-sync --dry-run)"
  src="$HOME/dev/agent-workforce/bin/agent_inbox_notion_sync.py"
  if [ -f "$src" ]; then
    run_or_note python3 "$src" --dry-run
  else
    echo "sync script missing: $src"
  fi

  section "Systemd timers (fleet schedule)"
  # W3 (2026-09-02): units come from config/fleet-units.tsv. The glob this replaced
  # ('overnight-*' 'agent-*' 'augustus-*' 'bd-*' 'weekly-*' + three names) matched 11 of the
  # 23 standing units, and still less than half. The shape of a glob is what hides that: a
  # prefix nobody thought to add is not a visible omission.
  # Measured 2026-09-02, expanding each file's glob prefixes against the standing set:
  # morning_report 8, eod_summary 9, daily_plan 10, and a three-way tie at 11 between
  # local_tier_eval, praetorium-status and this file. THE METHOD CHANGES THE ANSWER — count
  # literal names only and local_tier_eval scores 8, which is how an earlier revision of this
  # comment came to name a single "best". State the method with the number or it is not one.
  # Eight units were invisible to all six: buzz-pr-watch, content-change-dispatch, fleet-eval,
  # fleet-turn-check, inbox-backlog-alert, knowledge-digest, m1-signal-scan, raw-ingest.
  if [ ! -r "$FLEET_UNITS" ]; then
    echo "(FATAL: cannot read $FLEET_UNITS — unit coverage unknown, not 'nothing to report')"
  else
    mapfile -t _sys < <(fleet_or_die system timer)
    if [ ${#_sys[@]} -eq 0 ]; then
      echo "(UNKNOWN — see FATAL above; NOT 'no timers')"
    else
      run_or_note systemctl list-timers "${_sys[@]/%/.timer}" --no-pager
    fi

    section "Systemd timers (user scope)"
    # Separate call, separate manager. A user unit queried system-scope returns not-found,
    # which reads identically to a unit that has been removed.
    mapfile -t _usr < <(fleet_or_die user timer)
    if [ ${#_usr[@]} -gt 0 ]; then
      run_or_note env XDG_RUNTIME_DIR="/run/user/$(id -u)" \
        systemctl --user list-timers "${_usr[@]/%/.timer}" --no-pager
    else
      echo "(UNKNOWN — see FATAL above; NOT 'no user-scope timers')"
    fi

    section "Systemd services, user scope (kind=service — always-on, no timer)"
    # These have no next-elapse to report, so absence from the timer list above is correct
    # and their state has to be asked for separately. A permanently-live unit is exactly the
    # kind a schedule-shaped report renders as "never fired".
    mapfile -t _usrsvc < <(fleet_or_die user service)
    if [ ${#_usrsvc[@]} -gt 0 ]; then
      for u in "${_usrsvc[@]}"; do
        st=$(XDG_RUNTIME_DIR="/run/user/$(id -u)" \
               systemctl --user is-active "$u.service" 2>/dev/null || true)
        printf '  %-28s active=%s\n' "$u.service" "${st:-UNKNOWN}"
      done
    else
      echo "(UNKNOWN — see FATAL above; NOT 'no user-scope services')"
    fi

    section "Recent unit results"
    # KEY=VALUE, not --value. `systemctl show -p A -p B --value` prints in systemd's OWN
    # order, not the order of the flags, so the previous positional form silently mislabelled
    # every field it printed.
    # Result=success / ExecMainStatus=0 are systemd's RESET DEFAULTS, returned for a unit
    # that does not exist and for one that has never run since boot. Printing them unqualified
    # reports an uninstalled unit as healthy — agent-drift-check.service does exactly that
    # today, being declared in the manifests and absent from /etc. LoadState and an empty
    # ExecMainStartTimestamp are the two tells; both are checked before the values are shown.
    while read -r u; do
      [ -n "$u" ] || continue
      echo "--- $u.service ---"
      load=$(systemctl show "$u.service" -p LoadState --value 2>/dev/null)
      if [ "$load" != loaded ]; then
        echo "  NOT INSTALLED (LoadState=${load:-unknown}) — declared in design/agents/, absent from /etc"
        continue
      fi
      started=$(systemctl show "$u.service" -p ExecMainStartTimestamp --value 2>/dev/null)
      if [ -z "$started" ]; then
        echo "  NEVER RAN since boot — Result/ExecMainStatus below would be reset defaults, not outcomes"
        continue
      fi
      systemctl show "$u.service" \
        -p ActiveState -p Result -p ExecMainStatus -p ExecMainStartTimestamp 2>/dev/null \
        | paste -sd' ' - || echo "(unit unknown)"
    done < <(fleet_or_die system any)
  fi

  section "Box clock sanity"
  run_or_note timedatectl status

  section "Disk / system"
  run_or_note df -h /home
  run_or_note free -h

  section "Alerts (last 10)"
  # W17 (2026-09-03): the tail is DATED. A bare `tail -10` renders an eight-day-dead alert log
  # identically to a live one — presence is not freshness — and the consumer downstream is a
  # morning report whose whole job is to say what is wrong. Mirror-image of the readiness-report
  # trap already recorded against the readers, this time in the PRODUCER.
  #
  # "Print a timestamp" is NOT the fix, and that is the easy mistake here: every line
  # bin/agent_alert.sh writes already carries `failed at <ISO>Z` (:122), and ten such lines
  # from eight days ago still read as last night's to an LLM skimming the section. So the marker
  # states the AGE IN DAYS and labels the verdict in a word — `FRESH` / `STALE` — and a stale log
  # carries an explicit instruction not to report its lines as current. mtime is the authority
  # rather than the line text: the log is append-only (`>>`), so its mtime IS the moment the
  # newest entry was written, and it needs no parser that a reworded alert could break.
  #
  # Fail-soft like every other section: an unreadable mtime degrades to a stated UNKNOWN, never
  # to a crash and never to a silent blank — a blank here would read as freshness, which is the
  # defect being fixed. The `case` guards the arithmetic, because `$(( ))` on a non-numeric
  # value under `set -u` is an error, not a zero.
  alert_log="$HOME/logs/agent-alert.log"
  if [ -f "$alert_log" ]; then
    alert_mtime=$(stat -c %Y "$alert_log" 2>/dev/null || true)
    case "$alert_mtime" in
      ''|*[!0-9]*)
        echo "newest entry: UNKNOWN — could not read the mtime of $alert_log"
        echo "  The age of the lines below is UNVERIFIED. Do not report them as current."
        ;;
      *)
        alert_age=$(( ( $(date +%s) - alert_mtime ) / 86400 ))
        alert_when=$(date -d "@$alert_mtime" -Is 2>/dev/null || echo unknown)
        # This snapshot runs nightly, so last night's alert is 0 or 1 days old. Two days means
        # nothing has been written since before the PREVIOUS run — whatever is below is history.
        if [ "$alert_age" -ge 2 ]; then
          echo "newest entry: $alert_when ($alert_age days ago) — STALE"
          echo "  Nothing has been written to this log for $alert_age days. The lines below are"
          echo "  HISTORY, not last night's alerts — do not report them as current."
        else
          echo "newest entry: $alert_when ($alert_age days ago) — FRESH"
        fi
        ;;
    esac
    if [ -s "$alert_log" ]; then
      tail -10 "$alert_log" || true
    else
      echo "  (the log exists but is empty — no alerts recorded)"
    fi
  else
    echo "no agent-alert.log yet"
  fi
} >"$out" 2>&1

echo "wrote $out"
exit 0
